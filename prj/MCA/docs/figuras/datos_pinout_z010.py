# Clasificación (esto sí es a mano: agrupa las funciones de arriba en las
# categorías con las que pintan las figuras).
# --------------------------------------------------------------------------- #
def clase(bola):
    """Bola → categoría: io, nc, ddr, mio, ps, cfg, vcc, gnd."""
    banco, func, _, _ = PINES[bola]
    if func == "NC":
        return "nc"
    if func.startswith("IO_"):
        return "io"
    if func.startswith("PS_DDR"):
        return "ddr"
    if func.startswith("PS_MIO"):
        return "mio"
    if func.startswith("PS_"):
        return "ps"
    if func.startswith(("VCC", "RSVDVCC")):
        return "vcc"
    if func.startswith("GND") or func == "RSVDGND":
        return "gnd"
    return "cfg"


def corto(bola):
    """Bola → (etiqueta corta, calificador) para rotular la figura."""
    banco, func, _, marcas = PINES[bola]
    if func == "NC":
        return "NC", "7020"
    if func.startswith("IO_"):
        p = func.split("_")
        nombre = p[1] if p[1].startswith("L") else "IO" + p[1]
        extra = [x for x in p[2:-1]
                 if x in ("MRCC", "SRCC", "VREF", "DQS", "PUDC") or
                 x.startswith("AD")]
        return nombre, (banco + " " + extra[0]) if extra else banco
    if func.startswith("PS_DDR_"):
        return func[len("PS_DDR_"):].rsplit("_", 1)[0], "DDR"
    if func.startswith("PS_MIO"):
        return func[len("PS_"):].rsplit("_", 1)[0], banco
    if func.startswith("PS_"):
        return func[len("PS_"):].rsplit("_", 1)[0], "PS"
    if func.startswith("VCCO_"):
        return "VCCO", func[len("VCCO_"):].replace("_", " ")
    if func in ("VP_0", "VN_0"):
        return func[:2], "XADC"
    base = func.rsplit("_", 1)
    if len(base) == 2 and base[1] in ("0", "500", "501", "502"):
        return base[0], "cfg" if banco == "0" else banco
    return func, ""
